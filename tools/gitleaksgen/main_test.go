func TestNameSecretGroups(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name        string
		pattern     string
		secretGroup int
		want        string
	}{
		{"one group", `\b(ghp_[a-z]{4})\b`, 0, `\b(?P<value>ghp_[a-z]{4})\b`},
		{"no group", `ghp_[a-z]{4}`, 0, `ghp_[a-z]{4}`},
		{"non-capturing groups untouched", `(?:a|b)(c)(?i:d)`, 0, `(?:a|b)(?P<value>c)(?i:d)`},
		{"every group by default", `(a)|(b)`, 0, `(?P<value>a)|(?P<value>b)`},
		{"secret group only", `(login|token)=(\w+)`, 2, `(login|token)=(?P<value>\w+)`},
		{"named group kept when not the secret", `(?P<k>a)=(b)`, 2, `(?P<k>a)=(?P<value>b)`},
		{"named group renamed", `(?P<k>a)`, 0, `(?P<value>a)`},
		{"bracket in a class", `[(\]](x)[^]()]`, 0, `[(\]](?P<value>x)[^]()]`},
		{"escaped bracket", `\((x)\)`, 0, `\((?P<value>x)\)`},
		{"posix class", `[[:alpha:](](x)`, 0, `[[:alpha:](](?P<value>x)`},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			got, err := nameSecretGroups(tt.pattern, tt.secretGroup)
			if err != nil || got != tt.want {
				t.Errorf("nameSecretGroups(%q, %d) = %q, %v, want %q", tt.pattern, tt.secretGroup, got, err, tt.want)
			}
		})
	}
}

func TestNameSecretGroupsErrors(t *testing.T) {
	t.Parallel()

	for _, tt := range []struct {
		pattern     string
		secretGroup int
	}{{`(a)`, 2}, {`(a`, 0}} {
		if _, err := nameSecretGroups(tt.pattern, tt.secretGroup); err == nil {
			t.Errorf("nameSecretGroups(%q, %d) error = nil, want an error", tt.pattern, tt.secretGroup)
		}
	}
}

func TestReduce(t *testing.T) {
	t.Parallel()

	got, err := reduce("rule x", []allowlist{
		{Regexes: []string{`EXAMPLE$`}, Stopwords: []string{"Dummy"}},
		{Condition: "AND", Paths: []string{`\.bb$`}, Regexes: []string{`never`}},
		{Paths: []string{`README\.md$`}},
	})
	if err != nil {
		t.Fatal(err)
	}
	if strings.Join(got.regexes, ",") != "EXAMPLE$" || strings.Join(got.stopwords, ",") != "dummy" {
		t.Errorf("reduce() = %v %v, want the secret regex and the lowercased stopword only", got.regexes, got.stopwords)
	}

	for _, bad := range []allowlist{
		{RegexTarget: "line", Regexes: []string{"x"}},
		{Condition: "XOR"},
		{Regexes: []string{"("}},
	} {
		if _, err := reduce("rule x", []allowlist{bad}); err == nil {
			t.Errorf("reduce(%+v) error = nil, want an error", bad)
		}
	}
}

const sample = `title = "t"
minVersion = "v8.25.0"

[allowlist]
regexes = ['''^\$\w+$''']
stopwords = ["Example"]

[[rules]]
id = "zeta-token"
description = "Zeta"
regex = '''\b(zt_[a-z0-9]{8})\b'''
entropy = 2.5
keywords = ["zt_"]
[[rules.allowlists]]
regexes = ['''.+test$''']

[[rules]]
id = "alpha-key"
description = "Alpha"
regex = '''ak-[a-z]{8}'''
keywords = ["ak-"]

[[rules]]
id = "skip-me"
description = "Skipped"
regex = '''x'''
keywords = ["x"]

[[rules]]
id = "file-only"
description = "Path"
path = '''\.p12$'''
`

func TestRun(t *testing.T) {
	t.Parallel()

	in := filepath.Join(t.TempDir(), "gitleaks.toml")
	if err := os.WriteFile(in, []byte(sample), 0o600); err != nil {
		t.Fatal(err)
	}

	var out bytes.Buffer
	if err := run([]string{"-in", in, "-version", "v8.0.0", "-sha256", "abc", "-exclude", "skip-me"}, &out); err != nil {
		t.Fatal(err)
	}

	got := out.String()
	for _, want := range []string{
		"// Code generated by tools/gitleaksgen; DO NOT EDIT.",
		"gitleaks v8.0.0, SHA-256 abc",
		"Left out: skip-me (by choice); file-only (path-scoped).",
		"Copyright (c) 2019 Zachary Rice",
		`const gitleaksVersion = "v8.0.0"`,
		"`^\\$\\w+$`",
		`Stopwords: []string{"example"}`,
		"Pattern:  `\\b(?P<value>zt_[a-z0-9]{8})\\b`",
		"Entropy:  2.5",
		"`.+test$`",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("output lacks %q:\n%s", want, got)
		}
	}
	if strings.Index(got, "alpha-key") > strings.Index(got, "zeta-token") {
		t.Error("rules are not sorted by ID")
	}
	if strings.Contains(got, `"skip-me"`) {
		t.Error("excluded rule was generated")
	}
}

func TestRunErrors(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	write := func(name, content string) string {
		path := filepath.Join(dir, name)
		if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
		return path
	}
	unknownKey := write("unknown.toml", "future = 1\n")
	noKeywords := write("nokw.toml", "[[rules]]\nid = \"a\"\nregex = 'x'\n")
	upperKeyword := write("upper.toml", "[[rules]]\nid = \"a\"\nregex = 'x'\nkeywords = [\"X\"]\n")
	noRegex := write("noregex.toml", "[[rules]]\nid = \"a\"\nkeywords = [\"x\"]\n")

	tests := []struct {
		name string
		args []string
	}{
		{"missing flags", []string{"-in", unknownKey}},
		{"bad flag", []string{"-nope"}},
		{"missing file", []string{"-in", filepath.Join(dir, "missing"), "-version", "v", "-sha256", "s"}},
		{"unknown key", []string{"-in", unknownKey, "-version", "v", "-sha256", "s"}},
		{"no keywords", []string{"-in", noKeywords, "-version", "v", "-sha256", "s"}},
		{"uppercase keyword", []string{"-in", upperKeyword, "-version", "v", "-sha256", "s"}},
		{"no regex", []string{"-in", noRegex, "-version", "v", "-sha256", "s"}},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			if err := run(tt.args, &bytes.Buffer{}); err == nil {
				t.Errorf("run(%v) error = nil, want an error", tt.args)
			}
		})
	}
}
